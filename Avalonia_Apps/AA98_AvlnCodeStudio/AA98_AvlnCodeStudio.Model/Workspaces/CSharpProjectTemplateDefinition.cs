using System.Collections.Generic;

namespace AA98_AvlnCodeStudio.Model.Workspaces;

/// <summary>
/// Defines a project template that can be loaded from a JSON file.
/// </summary>
public sealed class CSharpProjectTemplateDefinition
{
    public string Id { get; set; } = string.Empty;

    public string Name { get; set; } = string.Empty;

    public string Description { get; set; } = string.Empty;

    public string DefaultProjectFileName { get; set; } = "{{ProjectName}}.csproj";

    public string ProjectFileContent { get; set; } = string.Empty;

    public List<CSharpProjectTemplateFile> Files { get; set; } = [];
}

/// <summary>
/// Defines one relative file generated by a project template.
/// </summary>
public sealed class CSharpProjectTemplateFile
{
    public string Path { get; set; } = string.Empty;

    public string Content { get; set; } = string.Empty;
}
